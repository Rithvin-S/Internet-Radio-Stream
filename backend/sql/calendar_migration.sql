-- ============================================================================
-- PulseCast Internet Radio Streaming System
-- Google Calendar-Style Admin Scheduling Migration (backend/sql/calendar_migration.sql)
-- Target: Supabase PostgreSQL (Postgres 15+)
--
-- Adds:
-- 1. Enhanced schedule metadata: schedule_date, category, status, artwork_url, timezone
-- 2. schedule_tracks: Associates multiple songs with a program schedule in playback order
-- ============================================================================

-- 1. Update public.program_schedules with calendar metadata
ALTER TABLE public.program_schedules
  ADD COLUMN IF NOT EXISTS schedule_date DATE DEFAULT CURRENT_DATE,
  ADD COLUMN IF NOT EXISTS category VARCHAR(50) DEFAULT 'Music',
  ADD COLUMN IF NOT EXISTS status VARCHAR(20) DEFAULT 'published',
  ADD COLUMN IF NOT EXISTS timezone VARCHAR(50) DEFAULT 'Asia/Kolkata',
  ADD COLUMN IF NOT EXISTS artwork_url VARCHAR(500),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

CREATE INDEX IF NOT EXISTS idx_schedules_date ON public.program_schedules (schedule_date);
CREATE INDEX IF NOT EXISTS idx_schedules_station_date ON public.program_schedules (station_id, schedule_date);

-- Trigger for program_schedules updated_at
DROP TRIGGER IF EXISTS trigger_schedules_updated_at ON public.program_schedules;
CREATE TRIGGER trigger_schedules_updated_at
  BEFORE UPDATE ON public.program_schedules
  FOR EACH ROW
  EXECUTE FUNCTION public.update_updated_at_column();

-- 2. Table: public.schedule_tracks
-- Associates ordered songs/streams with a program schedule
CREATE TABLE IF NOT EXISTS public.schedule_tracks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id BIGINT NOT NULL REFERENCES public.program_schedules(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  artist VARCHAR(200),
  album VARCHAR(200),
  duration VARCHAR(20) DEFAULT '03:45',
  duration_seconds INT DEFAULT 225,
  stream_url VARCHAR(500),
  play_order INT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_schedule_tracks_schedule ON public.schedule_tracks (schedule_id, play_order);

-- Enable RLS
ALTER TABLE public.schedule_tracks ENABLE ROW LEVEL SECURITY;

-- Allow public read access to schedule tracks
DROP POLICY IF EXISTS "Public can view schedule tracks" ON public.schedule_tracks;
CREATE POLICY "Public can view schedule tracks"
  ON public.schedule_tracks
  FOR SELECT
  TO anon, authenticated
  USING (TRUE);

-- Grant privileges
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT SELECT ON TABLE public.schedule_tracks TO anon, authenticated;
GRANT ALL ON TABLE public.schedule_tracks TO service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;

